#!/usr/bin/env python3
"""Package the manuscript-numbered figure set — sea_2026 (added 2026-07-28).

Copies the figure builder's output into output/figures/manuscript/ under the
manuscript-facing names, and regenerates FIGURE_MAP.md from the same table, so the map cannot
drift from what was actually copied.

Why this exists: the labeled set used to be produced by hand. On 2026-07-28 every file in it
was three weeks older than the generator output it claimed to mirror, and for Figures 5, 6 and 7
it was byte-identical to pre-2026-07-21 renders that no script writes any more. A missing or
stale source is now a hard failure rather than a silent mismatch.

PNG only. The builder also writes PDFs, but matplotlib stamps /CreationDate into every PDF, so
PDFs are not byte-reproducible and would break the hash ledger on each run. The PDFs stay in
output/figures/ for typesetting; the hash-covered set is PNG.

Usage: python3 code/analysis/05_package_figures.py   (runs from any CWD)
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import _runlog  # noqa: F401  (starts the run log; see docs/ and the README's Run logs section)
from _paths import FIGURES  # noqa: E402

# The builder writes working filenames into output/figures/; this step produces the
# manuscript-numbered set beside them, so a reader can go from "Figure 4" to a file without
# knowing the generator's internal naming.
SRC = FIGURES
DEST = FIGURES / "manuscript"

# (manuscript label, short caption, generator output, deposited name)
# Generator numbering matched manuscript numbering from 2026-07-21; the historical off-by-one in
# the SHAP figures is gone. Figure 4 became code-produced on 2026-07-28.
FIGURE_SET = [
    ("Figure 1", "Performance: basic hedonic vs XGB (rolling, by year)",
     "figure1_yearly_h1_xgb_fullsample.png", "Figure1_performance_hedonic_vs_xgb.png"),
    ("Figure 2a", "Transaction volume geography (district map)",
     "figure2_panel_a_with_names.png", "Figure2a_transaction_volume_map.png"),
    ("Figure 2b", "Price geography (district map)",
     "figure2_panel_b_with_names.png", "Figure2b_price_map.png"),
    ("Figure 3", "R2oos by model and forecast horizon (Full + Subsample)",
     "figure3_full_vs_subsample_split.png", "Figure3_r2_by_model_horizon.png"),
    ("Figure 4", "R2oos by district and over time (h=1, amenity subsample)",
     "figure4_appendix1_maintext_ready_subsample.png", "Figure4_r2_by_district_over_time.png"),
    ("Figure 5", "Top variables by SHAP importance",
     "figure5_mean_shap_district_dummy.png", "Figure5_top_shap_importance.png"),
    # Figure 6 is a two-panel exhibit as of 2026-08-01. Panel A is the six-category split over all
    # features; Panel B removes the district identifiers, whose per-district |SHAP| is that district's
    # level shift and which alone account for 56.2 of Gangnam's 58.0 location points. See
    # code/build/02_shap_bridges.py --district-out-of-location and decision_log.md.
    ("Figure 6 Panel A", "District-level characteristic category importance, all features",
     "figure6_shap_decomp_PanelA.png", "Figure6a_category_importance_by_district.png"),
    ("Figure 6 Panel B", "District-level characteristic category importance, district identifiers removed",
     "figure6_shap_decomp_PanelB.png", "Figure6b_category_importance_no_district.png"),
    ("Figure 7", "District ranking by time-feature attribution share",
     "figure7_time_share_ranking.png", "Figure7_district_time_share_ranking.png"),
    ("Figure 8", "Building characteristic importance heatmap",
     "figure8_building_shap_heatmap.png", "Figure8_building_importance_heatmap.png"),
]

MAP_NOTES = """
## Notes / caveats
- This file is GENERATED by `code/analysis/05_package_figures.py`. Do not hand-edit it;
  change the FIGURES table in that script instead.
- **Figure 4** is the amenity-subsample variant and is produced by
  `code/analysis/04_figures.py` from
  `data/derived/subsample_district_r2_all_horizons.csv` (written by `code/analysis/03_district_r2.py`).
  The render frozen on 2026-02-21 could not be tied to the deposited artifacts and is archived at
  the original archive's provenance notes.
- **Figure 7 semantics**: the filenames say `temporal_stability` and `temporal_sensitivity`, but
  the plotted quantity is a district ranking by the share of absolute SHAP attribution assigned to
  time features. The filenames do not establish cross-window temporal stability, market-phase
  sensitivity, or a temporal-stability test.
- **Figure 8** renders the raw 25x12 mean |SHAP| matrix. The historical render column-normalised
  it. Do not describe the two rendered images as transform-identical. See the original archive's provenance notes.
- PDFs are written alongside the PNGs in `output/figures/` and ARE hash-covered: `run_all.py` pins
  `SOURCE_DATE_EPOCH`, so matplotlib's timestamp is fixed and the PDFs are byte-reproducible.
- Generators (all read `data/derived/`):
  - Figs 1-8: `code/analysis/04_figures.py`
  - Fig 4 Panel A input: `code/analysis/03_district_r2.py`
  - Figs 5-8 bridge CSVs: `code/build/02_shap_bridges.py`
""".rstrip()


def main() -> int:
    DEST.mkdir(parents=True, exist_ok=True)

    missing = [src for _, _, src, _ in FIGURE_SET if not (SRC / src).exists()]
    if missing:
        print("[package-figures] FAIL: generator output missing:")
        for m in missing:
            print(f"    {SRC / m}")
        print("    Run code/analysis/04_figures.py first.")
        return 2

    for label, _caption, src, dest in FIGURE_SET:
        shutil.copyfile(SRC / src, DEST / dest)
        print(f"[package-figures] {label:>10}  {src}  ->  {dest}")

    rows = "\n".join(
        f"| {label} | {caption} | `{src}` | `{dest}` |"
        for label, caption, src, dest in FIGURE_SET
    )
    (DEST / "FIGURE_MAP.md").write_text(
        "# Figure mapping — manuscript Figure N -> canonical output\n\n"
        "Generated by `code/analysis/05_package_figures.py`. Every row is copied by that\n"
        "script on each run, so this table always describes the files actually present here.\n\n"
        "| Manuscript | Caption (short) | Generator output (`output/figures/`) | Deposited copy (this dir) |\n"
        "|---|---|---|---|\n"
        f"{rows}\n"
        f"{MAP_NOTES}\n",
        encoding="utf-8",
    )
    print(f"[package-figures] wrote {DEST / 'FIGURE_MAP.md'} ({len(FIGURE_SET)} figures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
